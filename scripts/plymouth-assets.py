def build_text(s, out, tmp):
    page = os.path.join(tmp, "text-%s.html" % set_name(s))
    open(page, "w").write(text_page(s))
    dom = chromium("file://" + page, 1400, 1400, dump=True)
    rects = json.loads(dom[dom.index("RECTS") + 5:dom.index("END", dom.index("RECTS"))])
    if not all(rects.pop("fonts")):
        sys.exit("fonts not loaded (DM Sans / Inter from Google Fonts): network?")
    shot = os.path.join(tmp, "text-%s.png" % set_name(s))
    chromium("file://" + page, 1400, 1400, shot=shot)
    img = Image.open(shot).convert("RGBA")
    entries = {}
    for name in ["lockup", "field-idle", "field-active", "field-error", "placeholder",
                 "msg-wrong", "msg-caps", "dot"]:
        x, y, w, h = rects[name]
        box = (math.floor(x) - 1, math.floor(y) - 1, math.ceil(x + w) + 1, math.ceil(y + h) + 1)
        img.crop(box).save(os.path.join(out, name + ".png"), optimize=True)
        # offset of the crop from the element's own box (fractional layout → whole pixels)
        entries[name] = {"file": name + ".png", "w": box[2] - box[0], "h": box[3] - box[1],
                         "ew": round(w, 3), "eh": round(h, 3), "dx": round(box[0] - x, 3), "dy": round(box[1] - y, 3)}
    # Layout of the passphrase block, relative to its top (cy + 184 s): prompt line, field, message line.
    fx, fy = rects["form"][:2]
    layout = {k: [round(v[0] - fx, 3), round(v[1] - fy, 3), round(v[2], 3), round(v[3], 3)]
              for k, v in rects.items() if k in ("prompt", "field", "message", "msgline")}
    return entries, layout


# --- generated script block ---------------------------------------------------------------------------------

def cubic_bezier(x1, y1, x2, y2, x):
    """CSS cubic-bezier(x1, y1, x2, y2) at progress x (bisection on the x curve)."""
    bez = lambda a, b, t: 3 * a * (1 - t) ** 2 * t + 3 * b * (1 - t) * t ** 2 + t ** 3
    lo, hi = 0.0, 1.0
    for _ in range(60):
        mid = (lo + hi) / 2
        lo, hi = (mid, hi) if bez(x1, x2, mid) < x else (lo, mid)
    return bez(y1, y2, (lo + hi) / 2)


# Curves of docs/PLYMOUTH.md (« Mouvements et courbes »), sampled for the script (no clock, no maths library).
EASINGS = {"EASE": (.25, .1, .25, 1), "EASE_IN_OUT": (.42, 0, .58, 1), "EASE_HALF_IN": (.16, .84, .24, 1),
           "EASE_RING_IN": (.2, .8, .2, 1), "EASE_SPIN": (.65, 0, .35, 1), "EASE_HALF_OUT": (.5, 0, .75, 0)}
EASE_STEPS = 100


def num(v):
    """Plain decimal for the Plymouth parser (no exponent, no « -0 »)."""
    text = ("%.5f" % v).rstrip("0").rstrip(".")
    return "0" if text in ("-0", "") else text


def script_block(sets, tiles):
    """Plymouth script has no include: the data lives in the theme script, between two markers."""
    out = [BEGIN, "// Do not edit: rerun scripts/plymouth-assets.py build.", "SETS = %d;" % len(sets),
           "TILES_PER_RING = %d;" % tiles, "RING_COUNT = %d;" % len(RINGS), "EASE_STEPS = %d;" % EASE_STEPS]
    for name, pts in sorted(EASINGS.items()):
        out.append(" ".join("%s[%d] = %s;" % (name, i, num(cubic_bezier(*pts, i / EASE_STEPS)))
                            for i in range(EASE_STEPS + 1)))
    for i, st in enumerate(sets):
        p = "SET[%d]" % i
        out.append('%s.s = %s; %s.dir = "%s/";' % (p, num(st["s"]), p, st["dir"]))
        for j, (f, *_rest) in enumerate(RINGS):
            out.append("%s.ring_r[%d] = %s;" % (p, j, num(f * 144 * st["s"])))
        for n, t in enumerate(st["tiles"]):
            out.append('%s.tile[%d].ring = %d; %s.tile[%d].file = "%s"; %s.tile[%d].x = %d; %s.tile[%d].y = %d; '
                       "%s.tile[%d].w = %d; %s.tile[%d].h = %d; %s.tile[%d].mx = %s; %s.tile[%d].my = %s;"
                       % (p, n, t["ring"], p, n, t["file"], p, n, t["x"], p, n, t["y"], p, n, t["w"], p, n, t["h"],
                          p, n, num(t["mx"]), p, n, num(t["my"])))
        out.append("%s.tile_count = %d;" % (p, len(st["tiles"])))
        for n, h in enumerate(st["halves"]):
            out.append('%s.half[%d].file = "%s"; %s.half[%d].side = %d;' % (p, n, h["file"], p, n, h["side"]))
        for name, e in sorted(st["text"].items()):
            key = name.replace("-", "_")
            out.append("%s.%s.dx = %s; %s.%s.dy = %s; %s.%s.ew = %s; %s.%s.eh = %s;"
                       % (p, key, num(e["dx"]), p, key, num(e["dy"]), p, key, num(e["ew"]), p, key, num(e["eh"])))
        for name, (x, y, w, h) in sorted(st["layout"].items()):
            out.append("%s.form_%s.x = %s; %s.form_%s.y = %s; %s.form_%s.w = %s; %s.form_%s.h = %s;"
                       % (p, name, num(x), p, name, num(y), p, name, num(w), p, name, num(h)))
    out.append(END)
    return "\n".join(out) + "\n"


def write_script_block(path, block):
    text = open(path).read() if os.path.exists(path) else ""
    if BEGIN in text:
        text = text[:text.index(BEGIN)] + block + text[text.index(END) + len(END) + 1:]
    else:
        text = block + text
    open(path, "w").write(text)


def build(args):
    scales = [float(x) for x in args.scales.split(",")]
    images = os.path.join(args.out, "images")
    sets = []
    shutil.rmtree(images, ignore_errors=True)       # wholly generated
    with tempfile.TemporaryDirectory() as tmp:
        for s in scales:
            d = os.path.join(images, set_name(s))
            os.makedirs(d)
            tiles = build_ring_tiles(s, args.tiles, d)
            halves = build_halves(s, d)
            text, layout = build_text(s, d, tmp)
            sets.append({"s": s, "dir": set_name(s), "tiles": tiles, "halves": halves, "text": text, "layout": layout})
            size = sum(os.path.getsize(os.path.join(d, f)) for f in os.listdir(d))
            print("%s: %d arcs, %d files, %.0f KiB" % (set_name(s), len(tiles), len(os.listdir(d)), size / 1024))
    for name, colour in (("crust", "crust"), ("mantle", "mantle")):      # 1 px, stretched to the band
        Image.new("RGBA", (1, 1), tuple(round(v * 255) for v in rgb(colour)) + (255,)).save(
            os.path.join(images, name + ".png"))
    json.dump(sets, open(args.layout, "w"), indent=1, sort_keys=True)
    write_script_block(os.path.join(args.out, "qs-corelab.script"), script_block(sets, args.tiles))


# --- check: rebuild a screen like Plymouth, compare with the reference --------------------------------------

def load_premul(path):
    a = np.asarray(Image.open(path).convert("RGBA"), np.float64)
    a[..., :3] *= a[..., 3:4] / 255
    return a


def ply_resize(img, w, h):
    """ply_pixel_buffer_resize: point-sampled bilinear, scale = (old - 1) / (new - 1)."""
    oh, ow = img.shape[:2]
    sx, sy = (ow - 1) / max(w - 1, 1), (oh - 1) / max(h - 1, 1)
    xs, ys = np.arange(w) * sx, np.arange(h) * sy
    ix, iy = xs.astype(int), ys.astype(int)
    fx, fy = (xs - ix)[None, :, None], (ys - iy)[:, None, None]
    ix1, iy1 = np.minimum(ix + 1, ow - 1), np.minimum(iy + 1, oh - 1)
    p00, p01 = img[iy][:, ix], img[iy][:, ix1]
    p10, p11 = img[iy1][:, ix], img[iy1][:, ix1]
    return p00 * (1 - fx) * (1 - fy) + p01 * fx * (1 - fy) + p10 * (1 - fx) * fy + p11 * fx * fy


def blend(canvas, img, x, y, opacity=1.0):
    h, w = img.shape[:2]
    H, W = canvas.shape[:2]
    x0, y0, x1, y1 = max(x, 0), max(y, 0), min(x + w, W), min(y + h, H)
    if x0 >= x1 or y0 >= y1:
        return
    src = img[y0 - y:y1 - y, x0 - x:x1 - x] * opacity
    dst = canvas[y0:y1, x0:x1]
    canvas[y0:y1, x0:x1] = src + dst * (1 - src[..., 3:4] / 255)


def pick_set(sets, s):
    """Smallest set at least as large as the screen (downscale only), else the largest."""
    bigger = [st for st in sets if st["s"] >= s - 1e-6]
    return min(bigger, key=lambda st: st["s"]) if bigger else max(sets, key=lambda st: st["s"])


def compose(images, sets, W, H, state, force_set=None):
    s = H / 1200
    st = force_set or pick_set(sets, s)
    f = s / st["s"]
    d = os.path.join(images, st["dir"])
    cx, cy = W // 2, H // 2
    canvas = np.zeros((H, W, 4))
    canvas[...] = [*(v * 255 for v in rgb("crust")), 255]
    scaled = lambda img: img if abs(f - 1) < 1e-9 else ply_resize(img, max(1, round(img.shape[1] * f)),
                                                                   max(1, round(img.shape[0] * f)))
    for t in st["tiles"]:
        x, y = cx + round(t["x"] * f), cy + round(t["y"] * f)
        if x > W or y > H or x + t["w"] * f < 0 or y + t["h"] * f < 0:
            continue
        blend(canvas, scaled(load_premul(os.path.join(d, t["file"]))), x, y)
    band = round(18 * s)
    blend(canvas, ply_resize(load_premul(os.path.join(images, "crust.png")), W, band), 0, cy - band // 2)
    filet = round(4 * s)
    blend(canvas, ply_resize(load_premul(os.path.join(images, "mantle.png")), W, filet), 0, cy - filet // 2)
    for h in st["halves"]:
        img = scaled(load_premul(os.path.join(d, h["file"])))
        blend(canvas, img, cx - img.shape[1] // 2, cy - img.shape[0] // 2)
    def put(name, ex, ey):
        """Image of an element whose own box starts at (ex, ey) on the screen (crop offset dx, dy)."""
        e = st["text"][name]
        blend(canvas, scaled(load_premul(os.path.join(d, e["file"]))), round(ex + e["dx"] * f), round(ey + e["dy"] * f))

    lock = st["text"]["lockup"]
    put("lockup", cx - lock["ew"] * f / 2, 1090 * s)
    if state == "error":
        lay = st["layout"]
        top = cy + 184 * s
        field_y = top + lay["field"][1] * f
        put("field-error", cx - lay["field"][2] * f / 2, field_y)
        ph = st["text"]["placeholder"]
        put("placeholder", cx - ph["ew"] * f / 2, field_y + (lay["field"][3] - ph["eh"]) * f / 2)
        msg = st["text"]["msg-wrong"]
        put("msg-wrong", cx - msg["ew"] * f / 2, top + lay["msgline"][1] * f)
    return canvas[..., :3].clip(0, 255).astype(np.uint8)


def check(args):
    images = os.path.join(args.out, "images")
    sets = json.load(open(args.layout))
    os.makedirs(args.shots, exist_ok=True)
    print("%-10s %-6s %-5s %8s %9s %9s" % ("screen", "state", "set", "mean", ">32 (%)", ">96 (%)"))
    for size in args.sizes.split(","):
        W, H = (int(v) for v in size.split("x"))
        for state in ("idle", "error"):
            ref = os.path.join(args.shots, "%s-%s-reference.png" % (size, state))
            if not os.path.exists(ref):
                chromium("file://%s?w=%d&h=%d&freeze=%s" % (REFERENCE, W, H, state), W, H, shot=ref)
            r = np.asarray(Image.open(ref).convert("RGB"), np.int16)
            variants = [None] + ([pick_set(sets, 99)] if args.from_largest else [])
            for force in variants:
                t = compose(images, sets, W, H, state, force)
                tag = "" if force is None else "-from-" + force["dir"]
                Image.fromarray(t).save(os.path.join(args.shots, "%s-%s-theme%s.png" % (size, state, tag)))
                diff = np.abs(t.astype(np.int16) - r).max(axis=2)
                Image.fromarray(np.clip(diff * 4, 0, 255).astype(np.uint8)).save(
                    os.path.join(args.shots, "%s-%s-diff%s.png" % (size, state, tag)))
                used = force or pick_set(sets, H / 1200)
                print("%-10s %-6s %-5s %8.2f %9.3f %9.3f%s" % (size, state, used["dir"], diff.mean(),
                      100 * (diff > 32).mean(), 100 * (diff > 96).mean(), "  (" + tag[1:] + ")" if tag else ""))


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    sub = ap.add_subparsers(dest="cmd", required=True)
    b = sub.add_parser("build")
    b.add_argument("--scales", default="0.9,1.0,1.2,1.5,1.8")
    b.add_argument("--tiles", type=int, default=16)
    b.add_argument("--out", default=THEME)
    b.add_argument("--layout", default=LAYOUT)
    c = sub.add_parser("check")
    c.add_argument("--sizes", default="1920x1080,1920x1200,2560x1440,3440x1440,3840x2160")
    c.add_argument("--out", default=THEME)
    c.add_argument("--layout", default=LAYOUT)
    c.add_argument("--shots", default=os.path.join(REPO, ".shots/plymouth"))
    c.add_argument("--from-largest", action="store_true", help="also compose every screen from the largest set")
    args = ap.parse_args()
    build(args) if args.cmd == "build" else check(args)


if __name__ == "__main__":
    main()
