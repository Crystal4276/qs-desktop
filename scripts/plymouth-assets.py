#!/usr/bin/env python3
"""Images of the Plymouth « Core Lab » theme (docs/PLYMOUTH.md), one set per scale s = screen height / 1200.

    plymouth-assets.py build [--scales 0.9,1.0,1.2,1.5,1.8] [--tiles 16] [--out DIR] [--layout FILE]
    plymouth-assets.py check [--sizes 1920x1080,1920x1200,2560x1440,3440x1440,3840x2160] [--shots DIR] [--layout FILE] [--from-largest]

build  draws every image of the theme for each scale:
         - dotted rings cut into arcs (r<ring>-<arc>.png): small sprites, tight boxes, whole dots only;
         - the four half-rings of the logo (half<k>.png), each in a square centred on the logo;
         - text and field images (lockup, field-*, placeholder, msg-*, dot) rendered by Chromium from the
           reference's own CSS and fonts (Google Fonts: DM Sans, Inter), transparent background.
       Positions go to the generated block of the theme script (between the GENERATED markers) and to the
       layout file read by check (kept out of the theme folder, which goes whole into the initramfs).
       One set per scale: Plymouth only resizes by point-sampled bilinear (no averaging), so a big set shrunk
       at boot blurs text and thins dots; the theme takes the smallest set at least as large as the screen.
check  rebuilds each screen the way Plymouth would (set chosen for the screen, Plymouth's own resize, sprites
       blended on crust) and compares it with a Chromium capture of assets/plymouth/reference/assemblage.html
       (freeze=idle and freeze=error). Writes <size>-<state>-{theme,reference,diff}.png and prints the gaps.

Developer tool only: needs python-cairo, python-numpy, python-pillow and chromium (network for the fonts).
"""
