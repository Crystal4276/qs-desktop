def rgb(name):
    h = C[name].lstrip("#")
    return tuple(int(h[i:i + 2], 16) / 255 for i in (0, 2, 4))


def set_name(s):
    return "s%03d" % round(s * 100)


def save_surface(surface, path):
    """cairo ARGB32 (premultiplied, native endian) → straight-alpha RGBA PNG, without metadata (reproducible)."""
    w, h = surface.get_width(), surface.get_height()
    a = np.ndarray((h, surface.get_stride() // 4, 4), np.uint8, surface.get_data())[:, :w]
    bgra = a.astype(np.float64)
    alpha = bgra[..., 3:4]
    with np.errstate(divide="ignore", invalid="ignore"):
        straight = np.where(alpha > 0, np.round(bgra[..., :3] * 255 / alpha), 0)
    out = np.dstack([straight[..., 2], straight[..., 1], straight[..., 0], bgra[..., 3]]).clip(0, 255).astype(np.uint8)
    Image.fromarray(out, "RGBA").save(path, optimize=True)


# --- rings ------------------------------------------------------------------------------------------------

def ring_dots(j, s):
    """Dot centres (x, y relative to the screen centre) of ring j at scale s: the reference's
    stroke-dasharray="0 gap" on an SVG circle starts at 3 o'clock and runs clockwise (y down)."""
    f, _, _, _, spacing = RINGS[j]
    r = f * 144 * s
    gap = spacing * 144 * s / 180
    n = math.ceil(2 * math.pi * r / gap - 1e-9)
    return r, [(r * math.cos(i * gap / r), r * math.sin(i * gap / r), i * gap / r) for i in range(n)]


def build_ring_tiles(s, tiles, out):
    """Arcs of every ring; arc k holds the dots whose angle falls in [(k - 1/2), (k + 1/2)] × 2π/tiles, so the
    seam at 3 o'clock (last dot almost on the first one on some rings) stays inside one sprite."""
    entries = []
    for j, (_, colour, opacity, thick, _) in enumerate(RINGS):
        r, dots = ring_dots(j, s)
        rad = thick * s / 2
        groups = {}
        for x, y, a in dots:
            k = int(((a + math.pi / tiles) % (2 * math.pi)) // (2 * math.pi / tiles))
            groups.setdefault(k, []).append((x, y))
        for k in sorted(groups):
            pts = groups[k]
            x0 = math.floor(min(x for x, _ in pts) - rad - 1)
            y0 = math.floor(min(y for _, y in pts) - rad - 1)
            x1 = math.ceil(max(x for x, _ in pts) + rad + 1)
            y1 = math.ceil(max(y for _, y in pts) + rad + 1)
            surface = cairo.ImageSurface(cairo.FORMAT_ARGB32, x1 - x0, y1 - y0)
            cr = cairo.Context(surface)
            for x, y in pts:          # one path, one fill: overlapping dots are not darker (like one SVG stroke)
                cr.new_sub_path()
                cr.arc(x - x0, y - y0, rad, 0, 2 * math.pi)
            cr.set_source_rgba(*rgb(colour), opacity)
            cr.fill()
            name = "r%02d-%02d.png" % (j + 1, k)
            save_surface(surface, os.path.join(out, name))
            # arc centre: where the arc sits on its ring (used to scale the ring around the screen centre)
            mid = (k * 2 * math.pi / tiles)
            entries.append({"ring": j, "file": name, "x": x0, "y": y0, "w": x1 - x0, "h": y1 - y0,
                            "mx": round(r * math.cos(mid), 2), "my": round(r * math.sin(mid), 2)})
    return entries


# --- half-rings -------------------------------------------------------------------------------------------

def build_halves(s, out):
    """Half-ring k: arc of mean radius k × 32 s, width 32 s, in an even square centred on the logo (rotation centre)."""
    entries = []
    unit = 32 * s
    for k, colour, side in HALVES:
        size = 2 * math.ceil((k + 0.5) * unit + 1)
        surface = cairo.ImageSurface(cairo.FORMAT_ARGB32, size, size)
        cr = cairo.Context(surface)
        cr.translate(size / 2, size / 2)
        if side > 0:
            cr.arc(0, 0, k * unit, -math.pi / 2, math.pi / 2)
        else:
            cr.arc_negative(0, 0, k * unit, -math.pi / 2, math.pi / 2)
        cr.set_line_width(unit)
        cr.set_line_cap(cairo.LINE_CAP_BUTT)
        cr.set_source_rgba(*rgb(colour), 0.9)
        cr.stroke()
        name = "half%d.png" % k
        save_surface(surface, os.path.join(out, name))
        entries.append({"file": name, "size": size, "side": side})
    return entries


