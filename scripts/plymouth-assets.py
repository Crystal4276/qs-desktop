def chromium(url, w, h, shot=None, dump=False):
    args = ["chromium", "--headless", "--disable-gpu", "--hide-scrollbars", "--no-first-run", "--mute-audio",
            "--force-device-scale-factor=1", "--default-background-color=00000000", "--virtual-time-budget=15000",
            "--window-size=%d,%d" % (w, h)]
    with tempfile.TemporaryDirectory() as profile:
        args.append("--user-data-dir=" + profile)
        args += ["--screenshot=" + shot] if shot else []
        args += ["--dump-dom"] if dump else []
        res = subprocess.run(args + [url], capture_output=True, text=True, timeout=120)
    if res.returncode != 0:
        sys.exit("chromium failed: " + res.stderr[-2000:])
    return res.stdout


